function ownership = buildTestOwnership(varargin)
%BUILDTESTOWNERSHIP Build and optionally validate canonical test ownership.
%
% ownership = buildTestOwnership()
% ownership = buildTestOwnership('WriteCsv', true)
% ownership = buildTestOwnership('ValidateActual', true)
%
% The proposed-owner rules are intentionally independent of runner nesting.
% This lets the same function describe a design before runner edits and then
% verify the implemented graph after the edits.  Reachability columns always
% describe the graph currently parsed by buildTestInventory.

parser = inputParser;
parser.addParameter('WriteCsv', false, @(x) islogical(x) && isscalar(x));
parser.addParameter('ValidateActual', false, @(x) islogical(x) && isscalar(x));
parser.parse(varargin{:});
options = parser.Results;

thisFile = mfilename('fullpath');
inventoryFolder = fileparts(thisFile);
[inventory, edges] = buildTestInventory();

tests = inventory(inventory.FileType == "test", :);
tests = sortrows(tests, 'Path');
runnerRows = inventory(inventory.FileType == "runner", :);
runnerPaths = string(runnerRows.Path);

runtimePath = fullfile(inventoryFolder, 'test_runtime_measurements.csv');
runtime = table();
if isfile(runtimePath)
    runtime = readtable(runtimePath, 'TextType', 'string');
end

testCount = height(tests);
canonicalRunner = strings(testCount, 1);
runtimeTier = strings(testCount, 1);
manualOnly = false(testCount, 1);
measuredSeconds = nan(testCount, 1);
evidence = strings(testCount, 1);
notes = strings(testCount, 1);

for i = 1:testCount
    entrypoint = string(tests.Entrypoint(i));
    [canonicalRunner(i), manualOnly(i), notes(i)] = proposedOwner(entrypoint, edges);
    runtimeTier(i) = tierForOwner(canonicalRunner(i), manualOnly(i));
    if ~isempty(runtime)
        match = find(runtime.Entrypoint == entrypoint, 1, 'last');
        if ~isempty(match)
            measuredSeconds(i) = runtime.ElapsedSecondsMedian(match);
        end
    end
    if manualOnly(i)
        evidence(i) = "documented manual registry; no normal runner execution";
    elseif isnan(measuredSeconds(i))
        evidence(i) = "static ownership design; runtime unmeasured";
    else
        evidence(i) = "static ownership design; measured child runtime available";
    end
end

runnerReach = buildRunnerReachability(runnerPaths, edges);
additionalRunners = strings(testCount, 1);
for i = 1:testCount
    reachedBy = strings(0, 1);
    for j = 1:numel(runnerPaths)
        if any(runnerReach{j} == string(tests.Path(i)))
            runnerName = runnerEntrypoint(runnerPaths(j), runnerRows);
            if runnerName ~= canonicalRunner(i)
                reachedBy(end + 1, 1) = runnerName; %#ok<AGROW>
            end
        end
    end
    additionalRunners(i) = strjoin(sort(unique(reachedBy)), ';');
end

ownership = table( ...
    string(tests.Path), string(tests.Entrypoint), string(tests.Category), ...
    runtimeTier, canonicalRunner, additionalRunners, manualOnly, ...
    reachableFrom("run_quick_contract_tests", tests.Path, runnerRows, runnerReach), ...
    reachableFrom("run_quick_smoke_tests", tests.Path, runnerRows, runnerReach), ...
    reachableFrom("run_numerical_regression_tests", tests.Path, runnerRows, runnerReach), ...
    reachableFrom("run_extended_integration_tests", tests.Path, runnerRows, runnerReach), ...
    reachableFrom("run_all_smoke_tests", tests.Path, runnerRows, runnerReach), ...
    measuredSeconds, evidence, notes, ...
    'VariableNames', { ...
    'TestPath', 'Entrypoint', 'Category', 'RuntimeTier', 'CanonicalRunner', ...
    'AdditionalAggregateRunners', 'ManualOnly', ...
    'ReachableFromQuickContracts', 'ReachableFromQuickSmoke', ...
    'ReachableFromNumericalRegression', 'ReachableFromExtendedIntegration', ...
    'ReachableFromHistoricalAllSmoke', 'MeasuredSeconds', 'Evidence', 'Notes'});

if options.ValidateActual
    validateActualOwnership(ownership, edges);
end

if options.WriteCsv
    writetable(ownership, fullfile(inventoryFolder, 'test_runner_ownership.csv'));
end
end

function [owner, manualOnly, notes] = proposedOwner(entrypoint, edges)
manualOnly = false;
notes = "";

groups = ownershipGroups();
for i = 1:numel(groups)
    if any(groups(i).Tests == entrypoint)
        owner = groups(i).Runner;
        return;
    end
end

testEdges = edges(edges.EdgeType == "runner_to_test" & ...
    edges.CalleeEntrypoint == entrypoint & edges.DirectOrDynamic ~= "reference_only", :);
callers = unique(string(testEdges.CallerEntrypoint));
if numel(callers) ~= 1
    error('buildTestOwnership:AmbiguousBaselineOwner', ...
        'No explicit ownership rule and %d executable direct runners for %s.', ...
        numel(callers), entrypoint);
end
owner = callers(1);
end

