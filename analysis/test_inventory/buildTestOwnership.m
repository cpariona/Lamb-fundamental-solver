function tier = tierForOwner(owner, manualOnly)
if manualOnly
    tier = "manual_deferred";
    return;
end
if any(owner == ["run_core_contract_tests", "run_execution_profile_contract_tests", ...
        "run_fit_data_import_tests", "run_fit_tool_interaction_contract_tests", ...
        "run_main_gui_export_tests", "run_mrlfe_public_api_contract_tests"])
    tier = "quick_contract";
elseif any(owner == ["run_gui_quick_tests", "run_ae_quick_tests", ...
        "run_mrlfe_smoke_tests"])
    tier = "quick_smoke";
elseif any(owner == ["run_core_numerical_regression_tests", ...
        "run_ae_extended_tests", ...
        "run_numerical_regression_tests", ...
        "run_mrlfe_production_core_contract_tests", ...
        "run_mrlfe_public_result_contract_tests"])
    tier = "numerical_regression";
elseif contains(owner, "performance") || owner == "run_performance_and_benchmark_tests"
    tier = "performance";
elseif contains(owner, "diagnostics")
    tier = "diagnostic";
elseif any(owner == ["run_mrlfe_public_contract_tests", ...
        "run_mrlfe_route_integrity_tests", ...
        "run_mrlfe_fit_public_solver_tests", ...
        "run_mrlfe_main_gui_public_solver_tests", ...
        "run_mrlfe_sweeptool_public_solver_tests", ...
        "run_mrlfe_neutral_production_helper_tests", ...
        "run_mrlfe_production_core_extended_tests"])
    tier = "characterization";
else
    tier = "extended_integration";
end
end

function runnerReach = buildRunnerReachability(runnerPaths, edges)
runnerReach = cell(numel(runnerPaths), 1);
for i = 1:numel(runnerPaths)
    pending = runnerPaths(i);
    visited = strings(0, 1);
    reachedTests = strings(0, 1);
    while ~isempty(pending)
        current = pending(1);
        pending(1) = [];
        if any(visited == current)
            continue;
        end
        visited(end + 1, 1) = current; %#ok<AGROW>
        outgoing = edges(edges.CallerPath == current & ...
            edges.DirectOrDynamic ~= "reference_only", :);
        reachedTests = [reachedTests; string(outgoing.CalleePath( ...
            outgoing.EdgeType == "runner_to_test"))]; %#ok<AGROW>
        nested = string(outgoing.CalleePath(outgoing.EdgeType == "runner_to_runner"));
        pending = [pending(:); nested(:)];
    end
    runnerReach{i} = sort(unique(reachedTests));
end
end

function result = reachableFrom(entrypoint, testPaths, runnerRows, runnerReach)
match = find(string(runnerRows.Entrypoint) == entrypoint & ...
    startsWith(string(runnerRows.Path), "tests/runners/"), 1);
result = false(height(testPaths), 1);
if isempty(match)
    return;
end
result = ismember(string(testPaths), runnerReach{match});
end

function name = runnerEntrypoint(path, runnerRows)
match = find(string(runnerRows.Path) == path, 1);
name = string(runnerRows.Entrypoint(match));
end

function validateActualOwnership(ownership, edges)
for i = 1:height(ownership)
    testName = ownership.Entrypoint(i);
    direct = edges(edges.EdgeType == "runner_to_test" & ...
        edges.CalleeEntrypoint == testName & ...
        edges.DirectOrDynamic ~= "reference_only", :);
    directOwners = unique(string(direct.CallerEntrypoint));
    if ownership.ManualOnly(i)
        assert(isempty(directOwners), ...
            'Manual-only test unexpectedly has a direct runner: %s', testName);
    else
        assert(isscalar(directOwners), ...
            'Expected exactly one direct runner for %s; found %d.', ...
            testName, numel(directOwners));
        assert(directOwners == ownership.CanonicalRunner(i), ...
            'Implemented direct owner for %s is %s, expected %s.', ...
            testName, directOwners, ownership.CanonicalRunner(i));
    end
end
