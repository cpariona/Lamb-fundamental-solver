clear; clc;
if isempty(which('mrlfeSolve'))
    startup
end

fprintf('\nRunning mRLFE execution profile benchmark contract test...\n');
fprintf('--------------------------------------------------------\n');

[resultsTable, summaryTable] = benchmarkMRLFEExecutionProfiles( ...
    'Mode', "contract", 'RepeatCount', 1, 'WriteCsv', false);

required = ["Surface", "Branch", "ViscosityCase", "RequestedProfile", ...
    "EffectiveProfile", "InternalSolverPreset", "InternalAtlasPreset", ...
    "GridPolicy", "InternalFrequencyCount", "RequestedFrequencyCount", ...
    "ValidFraction", "QualityAccepted", "QualityStatus", "FallbackApplied", ...
    "ElapsedSeconds", "MaxAbsCpDiffVsFast", "RmsCpDiffVsFast", ...
    "CommonValidCountVsFast", "RoutePolicy", "MetadataValid"];
assert(all(ismember(required, string(resultsTable.Properties.VariableNames))), ...
    'Benchmark result schema is missing required fields.');
assert(height(resultsTable) == 18 && height(summaryTable) == 18, ...
    'Contract mode should cover 3 surfaces x 3 profiles x 2 viscosity cases.');
assert(isequal(sort(unique(resultsTable.RequestedProfile)), ["Balanced"; "Fast"; "Robust"]), ...
    'All requested profiles must appear.');
assert(all(resultsTable.EffectiveProfile == resultsTable.RequestedProfile), ...
    'Effective profile must equal requested profile.');
assert(all(resultsTable.SupportMode == "direct"), 'mRLFE support mode must be direct.');
expectedPreset = lower(resultsTable.RequestedProfile);
assert(all(resultsTable.InternalSolverPreset == expectedPreset), ...
    'Internal solver preset must match Fast/Balanced/Robust.');
assert(all(resultsTable.InternalAtlasPreset == expectedPreset), ...
    'Internal atlas preset metadata must match the public preset.');
assert(~any(resultsTable.ProfileOverrideApplied), 'No mRLFE profile override may be applied.');
assert(all(resultsTable.MetadataValid), 'All benchmark metadata rows must satisfy the direct-profile contract.');
assert(all(resultsTable.FrequencyMonotonic), 'Requested frequency grids must be monotonic.');
assert(all(resultsTable.InternalFrequencyCount > 0 & resultsTable.RequestedFrequencyCount > 0), ...
    'Internal and requested frequency grids must be nonempty.');
mainOrFit = resultsTable.Surface == "Main" | resultsTable.Surface == "Fit";
assert(all(resultsTable.RequestedFrequencyCount(mainOrFit) == 10), ...
    'Contract mode Main/Fit cases must use the maintained ten-frequency minimum.');
assert(all(isfinite(resultsTable.ElapsedSeconds) & resultsTable.ElapsedSeconds >= 0), ...
    'Timing must be finite and nonnegative.');
assert(all(resultsTable.ValidFraction >= 0 & resultsTable.ValidFraction <= 1), ...
    'Validity fractions must be bounded.');
assert(all(resultsTable.CommonValidCountVsFast >= 0), ...
    'VsFast comparisons must report a nonnegative common-valid count.');

groupKeys = unique(resultsTable(:, {'Surface', 'Branch', 'ViscosityCase'}), 'rows');
for i = 1:height(groupKeys)
    mask = resultsTable.Surface == groupKeys.Surface(i) & ...
        resultsTable.Branch == groupKeys.Branch(i) & ...
        resultsTable.ViscosityCase == groupKeys.ViscosityCase(i);
    assert(isscalar(unique(resultsTable.RoutePolicy(mask))), ...
        'Route policy must remain independent of execution profile.');
end

% Numerical differences and validity-mask differences are descriptive. The
% contract deliberately has no equality or hardware timing threshold.
fprintf('mRLFE execution profile benchmark contract test passed.\n');
