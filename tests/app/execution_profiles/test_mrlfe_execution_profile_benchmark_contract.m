clear; clc;
startup

fprintf('\nRunning mRLFE execution profile benchmark contract test...\n');
fprintf('--------------------------------------------------------\n');

[resultsTable, summaryTable] = benchmarkMRLFEExecutionProfiles( ...
    'Repeats', 1, 'FitRepeats', 1, 'WriteCsv', false);

assert(height(resultsTable) == 18, ...
    'One-repeat mRLFE benchmark should cover 3 surfaces x 3 profiles x 2 eta states.');
assert(height(summaryTable) == 18, ...
    'Benchmark summary should include one row per surface/profile/eta state.');
assert(all(resultsTable.EffectiveProfile == "Fast"), ...
    'All mRLFE benchmark rows should preserve effective Fast.');
assert(all(resultsTable.SupportMode == "mapped_to_fast"), ...
    'All mRLFE benchmark rows should report mapped_to_fast.');
assert(all(resultsTable.RouteEqualVsFast), ...
    'mRLFE routes should match Fast within each surface and eta state.');
assert(all(resultsTable.ValidMaskEqualVsFast), ...
    'mRLFE valid masks should match Fast within each surface and eta state.');

fitRows = summaryTable.Surface == "Fit";
assert(all(summaryTable.OptionsEqualVsFast(fitRows)), ...
    'Fit mRLFE options should be equal to Fast after ignoring requested-profile metadata.');

nonFastMainOrSweep = (summaryTable.Surface == "Main" | summaryTable.Surface == "Sweep") & ...
    summaryTable.RequestedProfile ~= "Fast";
assert(any(~summaryTable.OptionsEqualVsFast(nonFastMainOrSweep)), ...
    'Main/Sweep non-Fast mRLFE should expose seed-option differences if present.');
assert(any(strlength(summaryTable.OptionDiffFieldsVsFast(nonFastMainOrSweep)) > 0), ...
    'Option differences should be listed for non-Fast Main/Sweep mRLFE cases.');

fprintf('mRLFE execution profile benchmark contract test passed.\n');
