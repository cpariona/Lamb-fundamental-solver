    'bounds', struct('mu', [1, 2]), ...
    'controls', struct('executionProfile', "Robust", 'robustness', "Fast")), ...
    'guiNormalizeExecutionProfile:ConflictingProfiles');

fprintf('Execution profile state transition contract test passed.\n');

function family = findFitFamily(registry, id)
for i = 1:numel(registry.modelFamilies)
    if string(registry.modelFamilies(i).id) == string(id)
        family = registry.modelFamilies(i);
        return;
    end
end
error('Missing FitTool family %s.', id);
end

function assertThrows(fcn, expectedId)
threw = false;
try
    fcn();
catch ME
    threw = true;
    assert(strcmp(ME.identifier, expectedId), ...
        'Expected error id %s, got %s.', expectedId, ME.identifier);
end
assert(threw, 'Expected function to throw %s.', expectedId);
end
