%TEST_MRLFE_MAINTAINED_ENTRYPOINTS_NAMING Guard maintained mRLFE naming surface.
%
% The maintained mRLFE execution surface should expose physical/model names.

repoRoot = testRepositoryRoot(mfilename('fullpath'));
forbiddenToken = char([72 97 110]);
forbiddenModelName = char([109 82 76 70 69 72 97 110 86 105 115 99 111 82 101 97 108 75]);

entrypointsPath = fullfile(repoRoot, 'docs', 'repository', 'maintained_entrypoints.md');
entrypointsText = fileread(entrypointsPath);
publicSection = extractSection(entrypointsText, '### mRLFE', '## Application APIs and helpers');
analysisSection = extractSection(entrypointsText, '### mRLFE analysis', ...
    '## Maintained internal model implementation');
internalSection = extractSection(entrypointsText, '### mRLFE production internals', '## Examples');

assert(~contains(entrypointsText, forbiddenToken), ...
    'Maintained entrypoints should not contain author-labeled names.');
publicNames = ["mrlfeSolve", "mrlfeDefaultParameters", "mrlfeDefaultOptions"];
for i = 1:numel(publicNames)
    assert(contains(publicSection, publicNames(i)), ...
        'Public mRLFE section is missing %s.', publicNames(i));
end
assert(~contains(publicSection, 'mrlfeTrackBranchAdaptive'), ...
    'Internal trackers must not be classified as public mRLFE API.');
assert(~contains(publicSection, 'mrlfeObjectiveResidual'), ...
    'Model residuals must not be classified as public mRLFE API.');

analysisNames = ["mrlfeSetYoungModulusForShearPoisson", ...
    "summarizeMRLFETrackingQuality"];
for i = 1:numel(analysisNames)
    assert(contains(analysisSection, analysisNames(i)), ...
        'mRLFE analysis section is missing %s.', analysisNames(i));
end
assert(~contains(analysisSection, 'mrlfeObjectiveResidual'), ...
    'Model residuals must not be classified as analysis helpers.');
assert(~contains(analysisSection, 'mrlfeEvaluatePhysicalTail'), ...
    'Model termination policies must not be classified as analysis helpers.');

internalNames = ["mrlfeObjectiveResidual", "mrlfeTrackBranchAdaptive", ...
    "mrlfeEvaluatePhysicalTail", "mrlfeApplyTerminationPolicy", ...
    "mrlfeValidateRequest", "mrlfeGetNumericalPreset"];
for i = 1:numel(internalNames)
    assert(contains(internalSection, internalNames(i)), ...
        'mRLFE internal section is missing %s.', internalNames(i));
end

assert(contains(entrypointsText, 'diagnose_mrlfe_fit_performance'), ...
    'Maintained diagnostics must list diagnose_mrlfe_fit_performance.');
assert(~contains(entrypointsText, 'stress_test_mrlfe_real_k_range'), ...
    'Maintained entrypoints must not list archived range diagnostics.');
assert(~contains(entrypointsText, 'solveMRLFEAtlasUnified'), ...
    'Maintained entrypoints must not list removed legacy solvers.');
assert(~contains(entrypointsText, 'diagnose_mrlfe_atlas_primary_policy_matrix'), ...
    'Maintained mRLFE section should not list the removed atlas primary policy diagnostic.');
assert(~contains(entrypointsText, 'diagnose_mrlfe_a0_policy_parametric_sweep'), ...
    'Maintained mRLFE section should not list deleted atlas policy diagnostics.');
assert(~contains(entrypointsText, 'run_mrlfe_atlas_tests'), ...
    'Maintained mRLFE section should not list removed atlas test runner.');
assert(~contains(entrypointsText, 'run_mrlfe_fit_atlas_tests'), ...
    'maintained_entrypoints.md should not list removed FitTool atlas test runner.');

newSweepEntrypoints = [ ...
    "mrlfe_sweep_mu_A0Like", ...
    "mrlfe_sweep_mu_S0Like", ...
    "mrlfe_sweep_etaS_A0Like", ...
