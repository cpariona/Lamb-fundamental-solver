function section = extractSection(text, startMarker, endMarker)
startIndex = strfind(text, startMarker);
endIndex = strfind(text, endMarker);
assert(~isempty(startIndex), 'Missing maintained-entrypoint section: %s.', startMarker);
endIndex = endIndex(endIndex > startIndex(1));
assert(~isempty(endIndex), 'Missing maintained-entrypoint section boundary: %s.', endMarker);
section = text(startIndex(1):endIndex(1)-1);
end
