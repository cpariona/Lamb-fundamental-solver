%TEST_MRLFE_MAINTAINED_ENTRYPOINTS_NAMING Guard maintained mRLFE naming surface.
%
% The maintained mRLFE execution surface should expose physical/model names.

repoRoot = testRepositoryRoot(mfilename('fullpath'));
forbiddenToken = char([72 97 110]);
forbiddenModelName = char([109 82 76 70 69 72 97 110 86 105 115 99 111 82 101 97 108 75]);

entrypointsPath = fullfile(repoRoot, 'docs', 'repository', 'maintained_entrypoints.md');
entrypointsText = fileread(entrypointsPath);
sectionStart = strfind(entrypointsText, '## mRLFE model');
sectionEnd = strfind(entrypointsText, '## Smoke-test scope');
assert(~isempty(sectionStart) && ~isempty(sectionEnd), ...
    'maintained_entrypoints.md must contain mRLFE and smoke-test sections.');

mrlfeSection = entrypointsText(sectionStart(1):sectionEnd(1)-1);
assert(~contains(mrlfeSection, forbiddenToken), ...
    'Maintained mRLFE section should not contain author-labeled names.');
assert(contains(mrlfeSection, 'mRLFEViscoRealK'), ...
    'Maintained mRLFE section should document the normalized viscous real-k model name.');
assert(contains(mrlfeSection, 'mrlfeSetYoungModulusForShearPoisson'), ...
    'Maintained mRLFE section should list mrlfeSetYoungModulusForShearPoisson.');
assert(contains(mrlfeSection, 'mrlfeSelectRealKBranches'), ...
    'Maintained mRLFE section should list mrlfeSelectRealKBranches.');
assert(contains(mrlfeSection, 'summarizeMRLFETrackingQuality'), ...
    'Maintained mRLFE section should list summarizeMRLFETrackingQuality.');
assert(contains(mrlfeSection, 'compareMRLFETrackingStrategies'), ...
    'Maintained mRLFE section should list compareMRLFETrackingStrategies.');
assert(contains(mrlfeSection, 'stress_test_mrlfe_real_k_range'), ...
    'Maintained mRLFE section should list the unified real-k range diagnostic.');
assert(~contains(mrlfeSection, 'solveMRLFEAtlasUnified'), ...
    'Maintained mRLFE section should not list removed legacy solvers.');
assert(contains(mrlfeSection, 'mrlfeTrackBranchAdaptive'), ...
    'Maintained mRLFE section should list mrlfeTrackBranchAdaptive.');
assert(contains(mrlfeSection, 'mrlfeA0Policy'), ...
    'Maintained mRLFE section should document the high-level A0 policy selector.');
assert(contains(mrlfeSection, 'diagnose_mrlfe_a0_policy_parametric_sweep'), ...
    'Maintained mRLFE section should list the A0 atlas policy parametric diagnostic.');
assert(~contains(mrlfeSection, 'run_mrlfe_atlas_tests'), ...
    'Maintained mRLFE section should not list removed atlas test runner.');
assert(~contains(entrypointsText, 'run_mrlfe_fit_atlas_tests'), ...
    'maintained_entrypoints.md should not list removed FitTool atlas test runner.');

newSweepEntrypoints = [ ...
    "mrlfe_sweep_mu_A0Like", ...
    "mrlfe_sweep_mu_S0Like", ...
    "mrlfe_sweep_etaS_A0Like", ...
    "mrlfe_sweep_etaS_S0Like", ...
    "mrlfe_sweep_thickness_A0Like", ...
    "mrlfe_sweep_thickness_S0Like" ...
    ];
for i = 1:numel(newSweepEntrypoints)
    assert(~isempty(which(newSweepEntrypoints(i))), ...
        'Missing maintained mRLFE sweep entrypoint: %s.', newSweepEntrypoints(i));
    assert(contains(mrlfeSection, newSweepEntrypoints(i)), ...
        'maintained_entrypoints.md is missing mRLFE sweep entrypoint: %s.', newSweepEntrypoints(i));
end

oldSweepEntrypoints = [ ...
    "sweep_mu_A0Like_viscoelastic", ...
    "sweep_mu_S0Like_viscoelastic", ...
    "sweep_etaS_A0Like_viscoelastic", ...
    "sweep_etaS_S0Like_viscoelastic", ...
    "sweep_thickness_A0Like_viscoelastic", ...
    "sweep_thickness_S0Like_viscoelastic" ...
    ];
for i = 1:numel(oldSweepEntrypoints)
    assert(isempty(which(oldSweepEntrypoints(i))), ...
        'Obsolete mRLFE sweep entrypoint should not resolve on the MATLAB path: %s.', oldSweepEntrypoints(i));
    assert(~contains(mrlfeSection, oldSweepEntrypoints(i)), ...
        'maintained_entrypoints.md should not list obsolete mRLFE sweep entrypoint: %s.', oldSweepEntrypoints(i));
end

