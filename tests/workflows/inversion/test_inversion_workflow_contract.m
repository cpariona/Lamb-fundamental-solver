function test_inversion_workflow_contract()
%TEST_INVERSION_WORKFLOW_CONTRACT Guard maintained human execution entrypoints.
% MATLAB Editor Run Section itself requires an interactive manual smoke check.
repoRoot = testRepositoryRoot(mfilename('fullpath'));
workflowRoot = fullfile(repoRoot, 'workflows');
functionRoot = fullfile(workflowRoot, 'inversion');
owners = ["run_rl_oce_inversion"; "run_ae_plate_oce_inversion"];
for owner = owners'
    sourceFile = fullfile(workflowRoot, owner + ".m");
    assert(isfile(sourceFile), 'Missing maintained human inversion driver: %s', owner);
    source = string(fileread(sourceFile));
    assert(~contains(source, "mfilename('fullpath')"), ...
        'Human Run Section must not resolve the MATLAB temporary script.');
    assert(contains(source, 'matlab.desktop.editor.getActiveFilename'), ...
        'Run Section needs the active MATLAB Editor file.');
    assert(contains(source, '[~, active_name, active_ext] = fileparts(char(workflow_file));') && ...
        contains(source, '''lamb:workflow:EditorFile'''), ...
        'Editor filename validation must avoid platform-specific separators.');
    assert(contains(source, 'fileparts(fileparts(char(workflow_file)))'), ...
        'Repository root must resolve above workflows/.');
    assert(~isfile(fullfile(functionRoot,owner+".m")), ...
        'Human Editor scripts belong at workflows/ root.');
    assert(contains(source, 'addpath(fullfile(projectRoot, ''workflows'', ''inversion'')'), ...
        'Opt-in workflow owner must be added after production startup.');
    assert(contains(source, 'addpath(fullfile(oce_repository_root, ''src'')'), ...
        'The OCE producer must be initialized explicitly.');
    assert(contains(source, 'prepareOceInversionObservations(study)'), ...
        'Workflow must consume the maintained shared observation coordinator.');
    assert(contains(source, 'resolveOceInversionPaths(study,') && ...
        contains(source, 'reviewOceInversionPhysics(') && ...
        contains(source, 'fitOceInversionNative(') && ...
        contains(source, 'persistOceInversionStudy(') && ...
        contains(source, 'renderOceInversionStudy('), ...
        'Human workflow must use the exact same execution owners as batch.');

    assert(contains(source, 'study.reuseOnly = true;') && ...
        contains(source, 'study.saveResult = false;') && ...
        contains(source, 'study.exportFigure = false;'), ...
        'Initial fitting and persistence must remain opt-in.');
    requiredSections = ["%% 1. USER CONFIGURATION", ...
        "%% 2. INITIALIZE", "%% 3. RECOVER", ...
        "%% 4. REVIEW", "%% 5.", "%% 6.", "%% 7."];
    for heading = requiredSections
        assert(contains(source, heading), ...
            'Workflow must expose section boundary %s: %s', heading, owner);
    end
end
assert(isfile(fullfile(functionRoot,'prepareOceInversionObservations.m')));
assert(isfile(fullfile(functionRoot,'oceInversionProvenance.m')));
assert(~isfile(fullfile(repoRoot,'studies','rlOceStudy.m')));
assert(~isfile(fullfile(repoRoot,'studies','aePlateOceStudy.m')));
assert(~isfile(fullfile(repoRoot,'studies','prepareOceStudyObservations.m')));
assert(~isfile(fullfile(repoRoot,'studies','oceStudyProvenance.m')));
rl = string(fileread(fullfile(workflowRoot,'run_rl_oce_inversion.m')));
plate = string(fileread(fullfile(workflowRoot,'run_ae_plate_oce_inversion.m')));
assert(contains(rl,'study.fullBandReviewed = false;') && ...
    contains(plate,'study.fullBandReviewed = false;'), ...
    'Both manual workflows must explicitly gate all-frequency fitting.');
assert(contains(rl, 'study.thicknessPolicy = "oce_directional_per_acquisition";') && ...
    contains(plate, 'study.thicknessPolicy = "oce_directional_per_acquisition";') && ...
    contains(plate, 'study.thicknessReferenceSourceIndex = NaN;'), ...
    'Both workflows must default to direction-matched OCE geometry.');
% Code-level checks only protect ownership and advertised interface names.
% Numerical thickness alignment and repeated-review behavior have functional tests.
assert(contains(rl,'''density_kgpm3''') && contains(rl,'''thickness_m''') && ...
    contains(rl,'''poisson_ratio''') && contains(rl,'''mu_Pa'''), ...
    'Human RL setup must expose canonical SI material inputs.');
fit=string(fileread(fullfile(functionRoot,'fitOceInversionNative.m')));
assert(contains(fit,'lamb.fitting.rayleigh_lamb.rlFitDispersionData') && ...
    contains(fit,'lamb.fitting.acoustoelastic_prestressed_plate.aePlateFitDispersion') && ...
    contains(fit,'fitOceQhPrestressedPlate'), ...
    'Shared execution must retain existing native scientific owners.');
for entry=["executeOceInversionStudy","runOceInversionBatch", ...
        "resolveOceInversionPaths","assertOceInversionReviewMatch"]
    assert(isfile(fullfile(functionRoot,entry+".m")), ...
        'Missing programmable inversion owner %s.',entry);
end
% The human experiment batch only discovers metadata and calls maintained owners.
batchFile=fullfile(workflowRoot,'run_experiment_inversion.m');
assert(isfile(batchFile),'Missing human experiment batch entrypoint.');
batch=string(fileread(batchFile));
assert(contains(batch,'matlab.desktop.editor.getActiveFilename') && ...
    contains(batch,'oce.results.recoverSummaryObservations') && ...
    contains(batch,'table2struct(groups(g,mechanical_keys))') && ...
    contains(batch,'runOceInversionBatch(plan,families(k))'), ...
    'Human batch must reuse the maintained OCE and Lamb APIs.');
assert(isfile(fullfile(functionRoot,'oceInversionConditionId.m')));
assert(contains(batch,'material = struct(') && contains(batch,'geometry = struct(') && ...
    contains(batch,'''density_kgpm3''') && ...
    contains(batch,'''poisson_ratio''') && ...
    contains(batch,'oceInversionConditionId(mechanical_keys,condition)') && ...
    ~contains(batch,'"condition_"+compose'), ...
    'Human Batch must use shared SI material inputs and stable condition IDs.');
% Human-editable approval and execution flags are not fixed test fixtures.
% Safety is enforced by the engine; here guard the explicit execute branch.
assert(contains(batch,'if ~run_batches') && ...
    contains(batch,'plan.execute = true;') && ...
    contains(batch,'fullBandReviewed') && ...
    ~contains(batch,'rlFitDispersionData(') && ...
    ~contains(batch,'aePlateFitDispersion('), ...
    'Human batch must gate execution and delegate all scientific fitting.');
% Renderer display override behavior is tested with actual function calls.
fprintf('Human inversion workflow structure and opt-in policy passed.\n');
end
